-- Reference / auth
-- ---------------------------------------------------------------------------

CREATE TABLE users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id     CHAR(26)        NOT NULL,
  full_name     VARCHAR(120)    NOT NULL,
  email         VARCHAR(255)    NOT NULL,
  password_hash VARCHAR(255)    NOT NULL,
  phone         VARCHAR(32)     NULL,
  role          VARCHAR(16)     NOT NULL,
  is_active     BOOLEAN         NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_users_public_id UNIQUE (public_id),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT chk_users_role CHECK (role IN ('customer', 'manager', 'admin'))
);

CREATE INDEX idx_users_role ON users (role);

CREATE TABLE rooms (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id     CHAR(26)        NOT NULL,
  room_number   VARCHAR(16)     NOT NULL,
  name          VARCHAR(120)    NOT NULL,
  room_type     VARCHAR(16)     NOT NULL,
  description   TEXT            NOT NULL,
  capacity      SMALLINT        NOT NULL,
  image_url     VARCHAR(500)    NOT NULL,
  base_price    NUMERIC(12, 2)  NOT NULL,
  is_active     BOOLEAN         NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_rooms_public_id UNIQUE (public_id),
  CONSTRAINT uq_rooms_room_number UNIQUE (room_number),
  CONSTRAINT chk_rooms_type CHECK (room_type IN ('standard', 'deluxe', 'suite', 'presidential')),
  CONSTRAINT chk_rooms_capacity CHECK (capacity >= 1),
  CONSTRAINT chk_rooms_base_price CHECK (base_price > 0)
);

CREATE INDEX idx_rooms_type ON rooms (room_type);

CREATE TABLE amenities (
  id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code  VARCHAR(64)  NOT NULL,
  label VARCHAR(120) NOT NULL,
  CONSTRAINT uq_amenities_code UNIQUE (code)
);

CREATE TABLE room_amenities (
  room_id     BIGINT NOT NULL,
  amenity_id  BIGINT NOT NULL,
  PRIMARY KEY (room_id, amenity_id),
  CONSTRAINT fk_room_amenities_room
    FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
  CONSTRAINT fk_room_amenities_amenity
    FOREIGN KEY (amenity_id) REFERENCES amenities (id) ON DELETE RESTRICT
);

CREATE TABLE room_month_settings (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id         BIGINT         NOT NULL,
  month_start     DATE           NOT NULL,
  is_available    BOOLEAN        NOT NULL DEFAULT TRUE,
  price_override  NUMERIC(12, 2) NULL,
  updated_by      BIGINT         NULL,
  created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_room_month UNIQUE (room_id, month_start),
  CONSTRAINT fk_room_month_room
    FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
  CONSTRAINT fk_room_month_updated_by
    FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT chk_room_month_day CHECK (EXTRACT(DAY FROM month_start) = 1),
  CONSTRAINT chk_room_month_price CHECK (price_override IS NULL OR price_override > 0)
);

CREATE INDEX idx_room_month_available ON room_month_settings (month_start, is_available);

CREATE TABLE room_blocks (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id     CHAR(26)        NOT NULL,
  room_id       BIGINT          NOT NULL,
  start_date    DATE            NOT NULL,
  end_date      DATE            NOT NULL,
  reason        VARCHAR(255)    NOT NULL,
  created_by    BIGINT          NULL,
  created_at    TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at    TIMESTAMPTZ(3)  NULL,
  CONSTRAINT uq_room_blocks_public_id UNIQUE (public_id),
  CONSTRAINT fk_room_blocks_room
    FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE RESTRICT,
  CONSTRAINT fk_room_blocks_created_by
    FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT chk_room_blocks_range CHECK (end_date >= start_date)
);

CREATE INDEX idx_room_blocks_range ON room_blocks (room_id, start_date, end_date);
CREATE INDEX idx_room_blocks_active ON room_blocks (room_id, deleted_at);

CREATE TABLE cart_items (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          BIGINT         NOT NULL,
  room_id          BIGINT         NOT NULL,
  check_in         DATE           NOT NULL,
  check_out        DATE           NOT NULL,
  nights           SMALLINT       NOT NULL,
  price_per_night  NUMERIC(12, 2) NOT NULL,
  total_amount     NUMERIC(12, 2) NOT NULL,
  created_at       TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_cart_user_room UNIQUE (user_id, room_id),
  CONSTRAINT fk_cart_user
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_cart_room
    FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE RESTRICT,
  CONSTRAINT chk_cart_dates CHECK (check_out > check_in),
  CONSTRAINT chk_cart_nights CHECK (nights >= 1),
  CONSTRAINT chk_cart_amounts CHECK (price_per_night > 0 AND total_amount > 0)
);

CREATE INDEX idx_cart_user ON cart_items (user_id);

CREATE TABLE orders (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id       CHAR(26)        NOT NULL,
  user_id         BIGINT          NULL,
  guest_name      VARCHAR(120)    NOT NULL,
  guest_email     VARCHAR(255)    NOT NULL,
  guest_phone     VARCHAR(32)     NOT NULL,
  currency        CHAR(3)         NOT NULL DEFAULT 'INR',
  subtotal_amount NUMERIC(12, 2)  NOT NULL,
  total_amount    NUMERIC(12, 2)  NOT NULL,
  status          VARCHAR(32)     NOT NULL DEFAULT 'pending_payment',
  source          VARCHAR(16)     NOT NULL,
  notes           VARCHAR(500)    NULL,
  created_by      BIGINT          NULL,
  created_at      TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_orders_public_id UNIQUE (public_id),
  CONSTRAINT fk_orders_user
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_orders_created_by
    FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT chk_orders_status CHECK (status IN (
    'pending_payment', 'paid', 'failed', 'cancelled', 'refunded'
  )),
  CONSTRAINT chk_orders_source CHECK (source IN ('online', 'walk-in', 'manager')),
  CONSTRAINT chk_orders_amounts CHECK (subtotal_amount >= 0 AND total_amount >= 0)
);

CREATE INDEX idx_orders_user ON orders (user_id);
CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_orders_guest_email ON orders (guest_email);

CREATE TABLE payments (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id             CHAR(26)        NOT NULL,
  order_id              BIGINT          NOT NULL,
  provider              VARCHAR(16)     NOT NULL DEFAULT 'razorpay',
  amount                NUMERIC(12, 2)  NOT NULL,
  currency              CHAR(3)         NOT NULL DEFAULT 'INR',
  status                VARCHAR(16)     NOT NULL DEFAULT 'created',
  razorpay_order_id     VARCHAR(64)     NULL,
  razorpay_payment_id   VARCHAR(64)     NULL,
  razorpay_signature    VARCHAR(255)    NULL,
  failure_reason        VARCHAR(255)    NULL,
  raw_payload           JSONB           NULL,
  paid_at               TIMESTAMPTZ(3)  NULL,
  created_at            TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at            TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_payments_public_id UNIQUE (public_id),
  CONSTRAINT uq_payments_razorpay_payment_id UNIQUE (razorpay_payment_id),
  CONSTRAINT fk_payments_order
    FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
  CONSTRAINT chk_payments_provider CHECK (provider IN ('razorpay', 'cash', 'card_at_desk', 'other')),
  CONSTRAINT chk_payments_status CHECK (status IN (
    'created', 'authorized', 'captured', 'failed', 'refunded'
  )),
  CONSTRAINT chk_payments_amount CHECK (amount > 0)
);

CREATE INDEX idx_payments_order ON payments (order_id);
CREATE INDEX idx_payments_razorpay_order ON payments (razorpay_order_id);

CREATE TABLE bookings (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id        CHAR(26)        NOT NULL,
  order_id         BIGINT          NOT NULL,
  room_id          BIGINT          NOT NULL,
  user_id          BIGINT          NULL,
  guest_name       VARCHAR(120)    NOT NULL,
  guest_email      VARCHAR(255)    NOT NULL,
  guest_phone      VARCHAR(32)     NOT NULL,
  check_in         DATE            NOT NULL,
  check_out        DATE            NOT NULL,
  nights           SMALLINT        NOT NULL,
  price_per_night  NUMERIC(12, 2)  NOT NULL,
  total_amount     NUMERIC(12, 2)  NOT NULL,
  status           VARCHAR(16)     NOT NULL DEFAULT 'confirmed',
  source           VARCHAR(16)     NOT NULL,
  notes            VARCHAR(500)    NULL,
  cancelled_at     TIMESTAMPTZ(3)  NULL,
  cancelled_by     BIGINT          NULL,
  created_at       TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_bookings_public_id UNIQUE (public_id),
  CONSTRAINT fk_bookings_order
    FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
  CONSTRAINT fk_bookings_room
    FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE RESTRICT,
  CONSTRAINT fk_bookings_user
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_bookings_cancelled_by
    FOREIGN KEY (cancelled_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT chk_bookings_status CHECK (status IN (
    'confirmed', 'modified', 'cancelled', 'checked_in', 'checked_out'
  )),
  CONSTRAINT chk_bookings_source CHECK (source IN ('online', 'walk-in', 'manager')),
  CONSTRAINT chk_bookings_dates CHECK (check_out > check_in),
  CONSTRAINT chk_bookings_nights CHECK (nights >= 1),
  CONSTRAINT chk_bookings_amounts CHECK (price_per_night > 0 AND total_amount > 0)
);

CREATE INDEX idx_bookings_room_dates ON bookings (room_id, check_in, check_out);
CREATE INDEX idx_bookings_user ON bookings (user_id);
CREATE INDEX idx_bookings_guest_email ON bookings (guest_email);
CREATE INDEX idx_bookings_status ON bookings (status);
CREATE INDEX idx_bookings_order ON bookings (order_id);

CREATE TABLE booking_events (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id    BIGINT          NOT NULL,
  actor_user_id BIGINT          NULL,
  event_type    VARCHAR(32)     NOT NULL,
  before_json   JSONB           NULL,
  after_json    JSONB           NULL,
  note          VARCHAR(500)    NULL,
  created_at    TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_booking_events_booking
    FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
  CONSTRAINT fk_booking_events_actor
    FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT chk_booking_events_type CHECK (event_type IN (
    'created', 'modified', 'cancelled', 'payment_linked', 'checked_in', 'checked_out'
  ))
);

CREATE INDEX idx_booking_events_booking ON booking_events (booking_id, created_at);

CREATE TABLE room_night_occupancy (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id       BIGINT          NOT NULL,
  stay_date     DATE            NOT NULL,
  source_type   VARCHAR(16)     NOT NULL,
  source_id     BIGINT          NOT NULL,
  created_at    TIMESTAMPTZ(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_room_night UNIQUE (room_id, stay_date),
  CONSTRAINT fk_occupancy_room
    FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
  CONSTRAINT chk_occupancy_source CHECK (source_type IN ('booking', 'block'))
);

CREATE INDEX idx_occupancy_source ON room_night_occupancy (source_type, source_id);

CREATE OR REPLACE VIEW v_room_effective_price AS
SELECT
  r.id AS room_id,
  r.room_number,
  r.name,
  r.room_type,
  r.base_price,
  rms.month_start,
  rms.is_available,
  COALESCE(rms.price_override, r.base_price) AS effective_price
FROM rooms r
LEFT JOIN room_month_settings rms ON rms.room_id = r.id
WHERE r.is_active = TRUE;

CREATE OR REPLACE VIEW v_active_bookings AS
SELECT
  b.*,
  r.room_number,
  r.name AS room_name,
  o.public_id AS order_public_id
FROM bookings b
JOIN rooms r ON r.id = b.room_id
JOIN orders o ON o.id = b.order_id
WHERE b.status <> 'cancelled';
